import pandas as pd
import numpy as np
import argparse
import os

def generate_features(filepath, val_col='invocations', k_sigma=3.0):
    if not os.path.exists(filepath):
        print(f"File {filepath} not found.")
        return None
        
    df = pd.read_csv(filepath)
    if val_col not in df.columns:
        print(f"Column {val_col} not found.")
        return None
        
    # Ensure timestamp is datetime
    if 'timestamp' in df.columns:
        df['timestamp'] = pd.to_datetime(df['timestamp'])
        df = df.sort_values('timestamp')
    else:
        print("No timestamp column found.")
        return None

    # Rename val_col to current_rps (assuming bucket represents RPS over interval)
    # The actual unit is "invocations per bucket".
    df['current_rps'] = df[val_col]
    
    # 1. Lag features
    for lag in [1, 2, 5, 10]:
        df[f'lag_{lag}'] = df['current_rps'].shift(lag)
        
    # 2. Rolling statistics
    for window in [5, 10, 30]:
        # min_periods=1 ensures we get values even at the beginning
        df[f'rolling_mean_{window}'] = df['current_rps'].rolling(window=window, min_periods=1).mean()
        df[f'rolling_std_{window}'] = df['current_rps'].rolling(window=window, min_periods=1).std().fillna(0)
        
    # 3. Burst indicator
    # Based on rolling mean and std to adapt to local context, or global?
    # User formula: RPS_t > mu + k * sigma
    # We will use the expanding mean and std so it doesn't peak into the future,
    # or rolling window. Let's use rolling_mean_30 and rolling_std_30.
    df['burst_indicator'] = (df['current_rps'] > (df['rolling_mean_30'] + k_sigma * df['rolling_std_30'])).astype(int)
    
    # 4. Temporal features
    df['hour'] = df['timestamp'].dt.hour
    df['minute'] = df['timestamp'].dt.minute
    df['day_of_week'] = df['timestamp'].dt.dayofweek
    
    # Fill NAs generated by shifts
    df = df.fillna(0)
    
    return df

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate Features")
    parser.add_argument("input_csv", help="Input timeseries CSV")
    parser.add_argument("output_csv", help="Output features CSV")
    parser.add_argument("--val-col", default="invocations", help="Column representing demand")
    parser.add_argument("--k-sigma", type=float, default=3.0, help="Threshold for burst detection")
    args = parser.parse_args()
    
    features_df = generate_features(args.input_csv, args.val_col, args.k_sigma)
    if features_df is not None:
        features_df.to_csv(args.output_csv, index=False)
        print(f"Features generated and saved to {args.output_csv}")
